"""
build_dataset.py -- enumerate every unlabelled simple graph with n <= 9 vertices
and store it with structural metadata.

The enumeration is complete and isomorph-free: generated by vertex extension and
reduced with the nauty certificate after every level.  The resulting counts match
three independent OEIS sequences (validated in src/validate.py):
    A000088  all graphs            1,2,4,11,34,156,1044,12346,274668
    A001349  connected graphs      1,1,2,6,21,112,853,11117,261080
    A121941  connected, deg <= 4   1,1,2,6,21,78,353,1929,12207

Output: results/graphs.jsonl.gz  (one JSON object per graph, sorted by n, graph6)
        results/dataset_summary.csv
"""

from __future__ import annotations

import csv
import gzip
import json
import multiprocessing as mp
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__))))

import networkx as nx
import graphlib as gl

FLAG_CONNECTED = 1
FLAG_PLANAR = 2
FLAG_BICONN = 4
FLAG_BIPARTITE = 8
FLAG_FOREST = 16
FLAG_TREE = 32
FLAG_CHEMICAL = 64        # connected and max degree <= 4
FLAG_CHEM_PLANAR = 128    # chemical and planar
FLAG_MGE4 = 256           # at least 4 edges (range where ERC is stated)


def flags_of(adj) -> int:
    n = len(adj)
    m = gl.n_edges(adj)
    conn = gl.connected(adj)
    maxd = gl.max_degree(adj) if n else 0
    G = nx.Graph()
    G.add_nodes_from(range(n))
    G.add_edges_from(gl.edges_of(adj))
    planar = bool(nx.check_planarity(G)[0]) if n else True
    f = 0
    if conn:
        f |= FLAG_CONNECTED
    if planar:
        f |= FLAG_PLANAR
    if gl.is_biconnected(adj):
        f |= FLAG_BICONN
    if gl.bipartite(adj):
        f |= FLAG_BIPARTITE
    if gl.is_forest(adj):
        f |= FLAG_FOREST
    if gl.is_forest(adj) and conn:
        f |= FLAG_TREE
    if conn and maxd <= 4:
        f |= FLAG_CHEMICAL
    if (f & FLAG_CHEMICAL) and planar:
        f |= FLAG_CHEM_PLANAR
    if m >= 4:
        f |= FLAG_MGE4
    return f


def _rec(adj):
    return {
        "g6": gl.to_graph6(adj),
        "n": len(adj),
        "m": gl.n_edges(adj),
        "ds": ",".join(str(d) for d in gl.degree_sequence(adj)),
        "fl": flags_of(adj),
        "ce": gl.canon_cert(adj).hex(),
    }


def main():
    t0 = time.time()
    workers = max(1, (os.cpu_count() or 4) - 2)
    levels = gl.enumerate_graphs_by_order(9)
    print(f"[{time.time()-t0:6.1f}s] enumerated", flush=True)
    allgraphs = []
    for n in range(1, 10):
        allgraphs.extend(levels[n].values())
    print(f"[{time.time()-t0:6.1f}s] {len(allgraphs)} graphs total", flush=True)

    recs = []
    with mp.Pool(workers) as pool:
        for i, r in enumerate(pool.imap(_rec, allgraphs, chunksize=256)):
            recs.append(r)
            if (i + 1) % 50000 == 0:
                print(f"[{time.time()-t0:6.1f}s] {i+1}/{len(allgraphs)}", flush=True)
    recs.sort(key=lambda r: (r["n"], r["g6"]))
    os.makedirs("results", exist_ok=True)
    with gzip.open("results/graphs.jsonl.gz", "wt", compresslevel=6) as f:
        for r in recs:
            f.write(json.dumps(r, separators=(",", ":")) + "\n")
    print(f"[{time.time()-t0:6.1f}s] wrote results/graphs.jsonl.gz", flush=True)

    rows = []
    for n in range(1, 10):
        sub = [r for r in recs if r["n"] == n]
        for label, test in [
            ("all", lambda r: True),
            ("connected", lambda r: r["fl"] & FLAG_CONNECTED),
            ("chemical(conn,deg<=4)", lambda r: r["fl"] & FLAG_CHEMICAL),
            ("chemical+planar", lambda r: r["fl"] & FLAG_CHEM_PLANAR),
            ("connected m>=4", lambda r: (r["fl"] & FLAG_CONNECTED) and (r["fl"] & FLAG_MGE4)),
            ("chemical m>=4", lambda r: (r["fl"] & FLAG_CHEMICAL) and (r["fl"] & FLAG_MGE4)),
        ]:
            rows.append({"n": n, "class": label, "count": sum(1 for r in sub if test(r))})
    with open("results/dataset_summary.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["n", "class", "count"])
        w.writeheader()
        w.writerows(rows)
    for r in rows:
        print(r)
    print(f"[{time.time()-t0:6.1f}s] done", flush=True)


if __name__ == "__main__":
    main()
